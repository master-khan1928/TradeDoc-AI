// русские буквы той же формы, что латинские, рисуются латинским глифом
const SAME_AS_LATIN = { А: "A", В: "B", Е: "E", К: "K", М: "M", Н: "H", О: "O", Р: "P", С: "C", Т: "T", Х: "X" };
for (const [ru, lat] of Object.entries(SAME_AS_LATIN)) G[ru] = G[lat];
const GLYPHS = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(" ")]));
export const SUPPORTED_CHARS = new Set(Object.keys(GLYPHS));

const CRC = new Int32Array(256).map((_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c; });
function crc32(buf) { let c = -1; for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8); return (c ^ -1) >>> 0; }
function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, "latin1"), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

/** Серое изображение (0 = чёрный, 255 = белый) -> PNG. */
export function encodePng(width, height, gray) {
  const raw = Buffer.alloc((width + 1) * height);
  for (let y = 0; y < height; y++) { raw[y * (width + 1)] = 0; gray.copy(raw, y * (width + 1) + 1, y * width, (y + 1) * width); }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0); ihdr.writeUInt32BE(height, 4); ihdr[8] = 8; ihdr[9] = 0; // 8 бит, оттенки серого
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw)), chunk("IEND", Buffer.alloc(0))]);
}

/**
 * Строки текста -> PNG. scale: размер пикселя шрифта; noise 0..1: «фото-подобный» серый шум (детерминированный).
 * Возвращает { png, text }: text — то, что реально нарисовано (заглавные, неизвестные знаки заменены на «?»).
 */
export function renderTextPng(lines, { scale = 3, noise = 0, seed = 1 } = {}) {
  const drawn = lines.map((l) => [...String(l).toUpperCase()].map((ch) => (SUPPORTED_CHARS.has(ch) ? ch : "?")).join(""));
  const cols = Math.max(1, ...drawn.map((l) => l.length)), margin = 4;
  const width = (cols * 6 + margin * 2) * scale, height = (drawn.length * 10 + margin * 2) * scale;
  const img = Buffer.alloc(width * height, 255);
  drawn.forEach((line, row) => {
    [...line].forEach((ch, col) => {
      GLYPHS[ch].forEach((bits, gy) => {
        for (let gx = 0; gx < 5; gx++) {
          if (bits[gx] !== "1") continue;
          const x0 = (margin + col * 6 + gx) * scale, y0 = (margin + row * 10 + gy) * scale;
          for (let dy = 0; dy < scale; dy++) img.fill(20, (y0 + dy) * width + x0, (y0 + dy) * width + x0 + scale);
        }
      });
    });
  });
  if (noise > 0) {
    let a = seed >>> 0;
    const rnd = () => { a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
    for (let i = 0; i < img.length; i++) img[i] = Math.max(0, Math.min(255, img[i] - 18 + Math.round((rnd() - 0.5) * 60 * noise)));
  }
  return { png: encodePng(width, height, img), text: drawn.join("\n"), width, height };
}
